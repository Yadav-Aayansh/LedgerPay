CREATE TABLE account (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   BIGINT         NOT NULL,
    balance    NUMERIC(19, 4) NOT NULL,
    version    BIGINT         NOT NULL,
    created_at TIMESTAMPTZ    NOT NULL
);

CREATE INDEX idx_account_owner ON account (owner_id);

-- Matches allocationSize = 50 on LedgerEntry
CREATE SEQUENCE ledger_entry_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE ledger_entry (
    id          BIGINT         PRIMARY KEY,
    account_id  BIGINT         NOT NULL REFERENCES account (id),
    amount      NUMERIC(19, 4) NOT NULL,
    transfer_id UUID           NOT NULL,
    created_at  TIMESTAMPTZ    NOT NULL
);

CREATE INDEX idx_ledger_account ON ledger_entry (account_id);
CREATE INDEX idx_ledger_transfer ON ledger_entry (transfer_id);

CREATE TABLE idempotency_key (
    idempotency_key VARCHAR(255) PRIMARY KEY,
    transfer_id     UUID,
    status          VARCHAR(20) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL
);
